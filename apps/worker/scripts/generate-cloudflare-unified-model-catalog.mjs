import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { createCloudflareUnifiedModelCatalogItem } from "../src/mcp/cloudflare-unified-model-catalog.ts";

const directory = "src/content/catalog-models";
const sourceUrl =
  "https://github.com/cloudflare/cloudflare-docs/tree/production/src/content/catalog-models";
const headers = { accept: "application/vnd.github+json", "user-agent": "crewhelm-model-catalog" };

async function json(url) {
  const response = await fetch(url, { headers });
  if (!response.ok) throw new Error(`Catalog request failed: ${response.status}`);
  return response.json();
}

const commits = await json(
  `https://api.github.com/repos/cloudflare/cloudflare-docs/commits?path=${directory}&sha=production&per_page=1`,
);
const sourceCommit = commits[0]?.sha;
if (typeof sourceCommit !== "string" || !/^[a-f0-9]{40}$/.test(sourceCommit)) {
  throw new Error("Catalog source commit was invalid.");
}
const files = await json(
  `https://api.github.com/repos/cloudflare/cloudflare-docs/contents/${directory}?ref=${sourceCommit}`,
);
if (!Array.isArray(files) || files.length === 0 || files.length > 500) {
  throw new Error("Catalog source file list was invalid.");
}
const models = [];
for (let offset = 0; offset < files.length; offset += 8) {
  const group = files.slice(offset, offset + 8);
  const raw = await Promise.all(
    group.map((file) => {
      if (file.type !== "file" || typeof file.download_url !== "string") {
        throw new Error("Catalog source file was invalid.");
      }
      return json(file.download_url);
    }),
  );
  models.push(
    ...raw.flatMap((model, index) => {
      const item = createCloudflareUnifiedModelCatalogItem(model, "bundled-fallback");
      if (item === null) {
        throw new Error(`Catalog source contained an invalid model: ${group[index]?.name}.`);
      }
      return item.runtimeCompatibility === "compatible" ? [item] : [];
    }),
  );
}
models.sort((left, right) => left.id.localeCompare(right.id));
if (new Set(models.map(({ id }) => id)).size !== models.length) {
  throw new Error("Catalog source contained duplicate models.");
}
const snapshot = {
  models,
  refreshedAt: new Date().toISOString(),
  sourceCommit,
  sourceUrl,
  status: "bundled-fallback",
};
const output = `// Generated by apps/worker/scripts/generate-cloudflare-unified-model-catalog.mjs.\n// Do not edit by hand.\nexport const bundledCloudflareUnifiedModelCatalog = ${JSON.stringify(snapshot, null, 2)} as const;\n`;
const destination = fileURLToPath(
  new URL("../src/mcp/cloudflare-unified-model-catalog.snapshot.ts", import.meta.url),
);
await writeFile(destination, output);
